#!/usr/bin/env node
// Generates docs/PARITY.md: every V40 page of packages/registry/registry.v2.json against the built app.
// A page is "Real page" when the web has a dedicated screen or the API has a typed / guarded module for it,
// "Generic register" when it is in the menu and served by the generic records engine, and "Not in the menu" otherwise.
// Usage: node scripts/gen-parity.cjs   (no database, no network)
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const v2 = JSON.parse(fs.readFileSync(path.join(root, 'packages/registry/registry.v2.json'), 'utf8'));
const v1 = JSON.parse(fs.readFileSync(path.join(root, 'packages/registry/registry.json'), 'utf8'));

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (e.name === 'node_modules' || e.name === 'dist' || e.name === 'tests') continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else if (/\.(ts|tsx)$/.test(e.name) && !/\.test\./.test(e.name)) out.push(p);
  }
  return out;
}

const menu = new Set();
for (const f of v1.families) for (const i of f.items) menu.add(i.id);
// pages added by later phases (the PHASE_ADDED_PAGES list)
const reg = fs.readFileSync(path.join(root, 'apps/api/src/core/registry.ts'), 'utf8');
for (const m of reg.matchAll(/^\s{4}id: '([a-z0-9-]+)',$/gm)) menu.add(m[1]);

const real = new Set();
const apiFiles = walk(path.join(root, 'apps/api/src'));
for (const f of apiFiles) {
  const s = fs.readFileSync(f, 'utf8');
  for (const m of s.matchAll(/(?:pageId|requirePageAction\()\s*:?\s*'([a-z0-9-]+)'/g)) real.add(m[1]);
}
const webFiles = walk(path.join(root, 'apps/web/src'));
for (const f of webFiles) {
  const s = fs.readFileSync(f, 'utf8');
  if (/ModulePage\.tsx$/.test(f)) for (const m of s.matchAll(/case '([a-z0-9-]+)':/g)) real.add(m[1]);
}

const rows = v2.pages.map((p) => {
  const inMenu = menu.has(p.id);
  const isReal = real.has(p.id);
  const status = !inMenu ? 'Not in the menu' : isReal ? 'Real page' : 'Generic register';
  return { id: p.id, title: p.title, family: p.family, tabs: (p.tabs || []).length, fields: (p.fields || []).length, buttons: (p.buttons || []).length, v2: p.status, status };
});

const count = (k) => rows.filter((r) => r.status === k).length;
const lines = [];
lines.push('# PARITY: V40 pages against the built ERP');
lines.push('');
lines.push(`Generated by \`node scripts/gen-parity.cjs\` from \`packages/registry/registry.v2.json\` (${rows.length} V40 pages). Nothing here is hand-edited.`);
lines.push('');
lines.push('| Result | Pages |');
lines.push('|---|---|');
lines.push(`| Real page (dedicated screen or typed module) | ${count('Real page')} |`);
lines.push(`| Generic register (in the menu, generic records engine) | ${count('Generic register')} |`);
lines.push(`| Not in the menu | ${count('Not in the menu')} |`);
lines.push('');
lines.push('"Real page" is a code-level check (the page has its own screen or guarded API). It does **not** compare tabs, fields and buttons one by one; that needs the browser (Phase 33 visual compare).');
lines.push('');
for (const fam of [...new Set(rows.map((r) => r.family))]) {
  lines.push(`## ${fam}`);
  lines.push('');
  lines.push('| Page | Title | V40 tabs | fields | buttons | Result |');
  lines.push('|---|---|---|---|---|---|');
  for (const r of rows.filter((x) => x.family === fam)) lines.push(`| ${r.id} | ${r.title} | ${r.tabs} | ${r.fields} | ${r.buttons} | ${r.status} |`);
  lines.push('');
}
fs.writeFileSync(path.join(root, 'docs/PARITY.md'), lines.join('\n'));
console.log(`PARITY.md written: real ${count('Real page')}, generic ${count('Generic register')}, not in menu ${count('Not in the menu')} of ${rows.length}`);
