/**
 * Generates docs/phases/STATUS.md (ERRATA E-36: generated, never hand-edited).
 * Reads: registry v2 (packages/registry/registry.v2.json), the screens that are real
 * (ModulePage cases, typed pages, GET /screens configs), the last crawler run
 * (tests/e2e/.artifacts/page-health.json) and the migration folders.
 * Run: npm run status:pages
 */
const fs = require('fs');
const path = require('path');

const root = process.cwd();
const read = (...p) => fs.readFileSync(path.join(root, ...p), 'utf8');
const v2 = JSON.parse(read('packages', 'registry', 'registry.v2.json'));

// --- which pages have a real screen today -------------------------------------------------
const modulePage = read('apps', 'web', 'src', 'pages', 'ModulePage.tsx');
const casePages = new Set([...modulePage.matchAll(/case '([a-z0-9-]+)':/g)].map((m) => m[1]));
const screenCfg = read('apps', 'api', 'src', 'modules', 'screens', 'configs.ts');
const screenPages = new Set([...screenCfg.matchAll(/^ {2}'([a-z0-9-]+)': \{$/gm)].map((m) => m[1]));
const kinds = read('apps', 'api', 'src', 'engine', 'kinds.ts');
const typed = new Set([...kinds.slice(0, kinds.indexOf('const typedPages')).matchAll(/'([a-z]+-[a-z0-9-]+)',/g)].map((m) => m[1]));
const apiRegistry = read('apps', 'api', 'src', 'core', 'registry.ts');
const added = [...apiRegistry.matchAll(/id: '([a-z0-9-]+)',\s*title: '([^']+)',\s*family: '([^']+)'/g)].map((m) => ({ id: m[1], title: m[2], family: m[3] }));

function kindOf(p) {
  if (p.status === 'planned') return 'planned';
  if (screenPages.has(p.id)) return 'screen';
  if (casePages.has(p.id)) return 'custom';
  if (typed.has(p.id)) return 'typed';
  return 'generic';
}
const rows = v2.pages.map((p, i) => ({ ...p, n: i + 1, kind: kindOf(p) }));
const count = (k) => rows.filter((r) => r.kind === k).length;

// --- crawler ---------------------------------------------------------------------------------
let crawl = null;
try {
  crawl = JSON.parse(read('tests', 'e2e', '.artifacts', 'page-health.json'));
} catch {
  crawl = null;
}

// --- migrations --------------------------------------------------------------------------------
const migDir = path.join(root, 'apps', 'api', 'prisma', 'migrations');
const migs = fs
  .readdirSync(migDir, { withFileTypes: true })
  .filter((e) => e.isDirectory())
  .map((e) => e.name)
  .sort();
function phaseOfMigration(name) {
  const m = /_phase0?(\d+b?)_/i.exec(name) || /_p(\d+)_/i.exec(name);
  return m ? `P${m[1].toUpperCase()}` : '—';
}
function descOf(name) {
  const f = path.join(migDir, name, 'migration.sql');
  if (!fs.existsSync(f)) return '';
  const first = fs.readFileSync(f, 'utf8').split('\n').find((l) => l.startsWith('--'));
  return (first || '').replace(/^--\s*/, '').replace(/\|/g, '/').slice(0, 140).trim();
}

let md = `# Project Implementation Status & Registry Matrix

This page is generated by \`npm run status:pages\` from registry v2, the code and the last crawler run. Do not edit it by hand.

## 1. Summary

| | Count |
|---|---|
| V40 pages in registry v2 | ${rows.length} |
| Built (screen / custom / typed) | ${count('screen') + count('custom') + count('typed')} |
| Built but still on the generic record engine | ${count('generic')} |
| Planned (owner phase 23–31) | ${count('planned')} |
| Pages added after V40 by a later phase | ${added.length} |
| Migrations | ${migs.length} |
| Crawler: last run | ${crawl ? `${crawl.checks.length} checks, ${crawl.checks.filter((c) => c.status === 'ERROR').length} errors` : 'not run yet'} |

## 2. Pages (registry v2)

| # | Page ID | Title | Family | Screen today | Owner phase |
|---|---|---|---|---|---|
`;
for (const r of rows) {
  md += `| ${r.n} | \`${r.id}\` | ${r.title} | ${r.family} | \`${r.kind}\` | ${r.ownerPhase ? `P${r.ownerPhase}` : r.changedOnPurpose ? '(changed on purpose)' : ''} |\n`;
}
md += `\n### Pages added after V40 (not in V40, built)\n\n| Page ID | Title | Family |\n|---|---|---|\n`;
for (const a of added) md += `| \`${a.id}\` | ${a.title} | ${a.family} |\n`;

md += `\n## 3. Migrations\n\n| Migration | Phase | What |\n|---|---|---|\n`;
for (const m of migs) md += `| \`${m}\` | ${phaseOfMigration(m)} | ${descOf(m)} |\n`;

if (crawl) {
  const bad = crawl.checks.filter((c) => c.status === 'ERROR');
  md += `\n## 4. Page health (last crawler run)\n\n${crawl.checks.length} checks, ${bad.length} errors.\n\n`;
  if (bad.length) {
    md += '| Page | Role | Plants | Problem |\n|---|---|---|---|\n';
    for (const b of bad.slice(0, 100)) md += `| \`${b.page_id}\` | ${b.role_code} | ${b.unit_combo} | ${String(b.error_text || b.error_kind).replace(/\|/g, '/').slice(0, 160)} |\n`;
  }
}

const out = path.join(root, 'docs', 'phases', 'STATUS.md');
fs.writeFileSync(out, md);
console.log(`STATUS.md: ${rows.length} pages (${count('screen')} screen, ${count('custom')} custom, ${count('typed')} typed, ${count('generic')} generic, ${count('planned')} planned), ${migs.length} migrations`);
