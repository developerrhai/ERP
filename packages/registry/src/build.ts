// Turns the parsed prototype literals into the typed Registry and renders registry.d.ts.
// Kept apart from extract.ts so tests can rebuild the registry in memory.
import { extractInlineScript, parsePrototype } from "./parse.js";
import { asObject, asStringArray, toFamilies, toProfile, toStringArrayRecord } from "./validate.js";
import type { Profile, Registry } from "../registry.js";

export function buildRegistry(html: string, generatedFrom: string, sha256: string): Registry {
  const { literals, overrides } = parsePrototype(extractInlineScript(html));

  const rawProfiles = asObject(literals.PROFILES, "PROFILES");
  for (const { profileId, patch } of overrides) {
    const target = asObject(rawProfiles[profileId], `PROFILES["${profileId}"]`);
    Object.assign(target, patch); // same semantics as the prototype's runtime Object.assign
  }
  const profiles: Record<string, Profile> = {};
  for (const [id, raw] of Object.entries(rawProfiles)) {
    profiles[id] = toProfile(raw, `PROFILES["${id}"]`);
  }

  return {
    generatedFrom,
    sha256,
    families: toFamilies(literals.MENU),
    profiles,
    deptFamilies: toStringArrayRecord(literals.DEPT_FAMILIES, "DEPT_FAMILIES"),
    departments: asStringArray(literals.DEPARTMENTS, "DEPARTMENTS"),
  };
}

const TYPES_BODY = `export interface MenuItem {
  readonly id: string;
  readonly title: string;
}

export interface Family {
  readonly name: string;
  readonly icon: string;
  readonly items: readonly MenuItem[];
}

export interface Profile {
  readonly title: string;
  readonly family: string;
  readonly purpose: string;
  readonly tabs: readonly string[];
  readonly fields: readonly string[];
}

export interface Registry {
  readonly generatedFrom: string;
  readonly sha256: string;
  readonly families: readonly Family[];
  readonly profiles: Readonly<Record<string, Profile>>;
  readonly deptFamilies: Readonly<Record<string, readonly string[]>>;
  readonly departments: readonly string[];
}
`;

function union(values: readonly string[]): string {
  return values.map((v) => `  | ${JSON.stringify(v)}`).join("\n");
}

export function renderTypes(registry: Registry): string {
  const ids = registry.families.flatMap((f) => f.items.map((i) => i.id));
  return [
    `// GENERATED by \`npm run extract\` from ${registry.generatedFrom}; do not edit by hand.`,
    "// Types for registry.json, shared by the extractor, the API and the web app.",
    "",
    TYPES_BODY,
    "/** Every menu item id, in menu order. */",
    `export type MenuId =\n${union(ids)};`,
    "",
    "/** The departments, in prototype order. */",
    `export type Department =\n${union(registry.departments)};`,
    "",
  ].join("\n");
}
