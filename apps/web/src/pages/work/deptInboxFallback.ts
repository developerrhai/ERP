import type { MailRow } from '../../lib/docsMailApi';
import type { Movement, MovementState } from '../../lib/workApi';

export type InboxRow =
  | { kind: 'move'; at: string; m: Movement }
  | { kind: 'mail'; at: string; mail: MailRow };

function makeMovement(
  id: string,
  num: string,
  docType: string,
  docNo: string,
  fromDept: string,
  toDept: string,
  state: MovementState,
  routeType: string,
  workStatus: string,
  priority: 'Normal' | 'High' | 'Critical',
  handoverNote: string,
  daysAgo: number,
  returnReason?: string,
): Movement {
  const d = new Date(Date.now() - daysAgo * 86400000);
  const sentAt = d.toISOString();
  const receivedAt = state !== 'SENT' ? new Date(d.getTime() + 3600000).toISOString() : null;
  const acceptedAt = ['ACCEPTED', 'IN_WORK', 'WAITING_APPROVAL', 'COMPLETED', 'FORWARDED'].includes(state)
    ? new Date(d.getTime() + 7200000).toISOString()
    : null;
  const slaDue = new Date(d.getTime() + 48 * 3600000).toISOString();

  return {
    id,
    number: num,
    unit_id: 'u-main-plant',
    to_unit_id: null,
    doc_type: docType,
    doc_id: `doc-${id}`,
    doc_no: docNo,
    from_department_id: `dept-${fromDept.toLowerCase()}`,
    from_department: fromDept,
    to_department_id: `dept-${toDept.toLowerCase()}`,
    to_department: toDept,
    assigned_manager_id: 'mgr-01',
    assigned_manager: `${toDept} Manager`,
    route_type: routeType,
    priority,
    required_by: new Date(Date.now() + 3 * 86400000).toISOString().slice(0, 10),
    work_status: workStatus,
    handover_note: handoverNote,
    state,
    sent_at: sentAt,
    received_at: receivedAt,
    accepted_at: acceptedAt,
    return_reason: returnReason ?? null,
    sla_due_at: slaDue,
    is_late: false,
    is_physical: false,
    version: 1,
    sent_by: `${fromDept} Supervisor`,
    received_by: state !== 'SENT' ? `${toDept} Inward Clerk` : null,
    accepted_by: acceptedAt ? `${toDept} Officer` : null,
  };
}

function makeMail(
  id: string,
  subject: string,
  fromDept: string,
  fromName: string,
  daysAgo: number,
  read: boolean,
  attachments: number,
): MailRow {
  const d = new Date(Date.now() - daysAgo * 86400000);
  return {
    id,
    subject,
    from_department: fromDept,
    from_name: fromName,
    created_at: d.toISOString(),
    read,
    attachments,
  };
}

